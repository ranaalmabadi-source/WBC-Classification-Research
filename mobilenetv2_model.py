# 2) Grab the exact layer objects from your saved model
base = loaded_model.get_layer('my_mobilenet_base')
gap  = loaded_model.get_layer('global_average_pooling2d')
bn   = loaded_model.get_layer('batch_normalization')
fc1  = loaded_model.get_layer('dense')
do   = loaded_model.get_layer('dropout')
fc2  = loaded_model.get_layer('dense_1')

# 3) Load & preprocess image
img_array = get_img_array(SAMPLE_IMAGE_PATH, size=IMAGE_SIZE)
img_tensor = tf.convert_to_tensor(img_array)

# 4) Forward pass layer-by-layer
with tf.GradientTape() as tape:
    # base features
    feats = base(img_tensor, training=False)
    tape.watch(feats)

    # head
    x = gap(feats)
    x = bn(x, training=False)
    x = fc1(x)
    x = do(x, training=False)
    logits = fc2(x)
    preds = tf.nn.softmax(logits)

    # pick top predicted class
    pred_index = tf.argmax(preds[0])
    target = preds[:, pred_index]

# 5) Grad-CAM heatmap from feats -> target class
grads = tape.gradient(target, feats)
pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))
feats = feats[0]
heatmap = feats @ pooled_grads[..., tf.newaxis]
heatmap = tf.squeeze(heatmap)
heatmap = tf.maximum(heatmap, 0) / (tf.reduce_max(heatmap) + K.epsilon())
heatmap = heatmap.numpy()

print(f"Pred idx={int(pred_index.numpy())}, prob={float(preds[0, pred_index]):.4f}, feats={feats.shape}")
show_gradcam(SAMPLE_IMAGE_PATH, heatmap)